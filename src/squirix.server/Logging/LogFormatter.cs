namespace Squirix.Server.Logging;

/// <summary>Formats structured log templates for the Squirix server.</summary>
internal static class LogFormatter
{
    /// <summary>Returns <paramref name="template" /> unchanged as a normalized log template.</summary>
    /// <param name="template">The template to normalize.</param>
    /// <returns>The normalized template.</returns>
    internal static string Format(string template) => template;
}
